using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading;
using System.Threading.Tasks;
using YoutubeExplode;
using YoutubeExplode.Videos;
using YoutubeExplode.Videos.ClosedCaptions;
using YoutubeExplode.Videos.Streams;
using YoutubeExplode.Converter;

using PremiumYoutubeDownloader.Models;

namespace PremiumYoutubeDownloader.Services;

public class VideoDownloaderService
{
    public const string HighestMp3Preference = "Highest Quality MP3";
    public const string BestVideoPreference = "Best Video (Up to 8K)";
    public const string NativeVideoPreference = "Highest Video (Native)";
    public const string Video1080pPreference = "1080p Video (Requires FFmpeg)";
    public const string Video720pPreference = "720p Video (Requires FFmpeg)";

    private readonly YoutubeClient _youtube;

    public VideoDownloaderService()
    {
        _youtube = new YoutubeClient(YoutubeHttpClientFactory.Create());
    }

    public async Task<Video> GetVideoDetailsAsync(string url, CancellationToken cancellationToken = default)
    {
        return await _youtube.Videos.GetAsync(url, cancellationToken);
    }

    public async Task<ClosedCaptionTrackInfo?> FindSubtitleTrackAsync(
        string url,
        string languageCode,
        CancellationToken cancellationToken = default)
    {
        try
        {
            var manifest = await _youtube.Videos.ClosedCaptions.GetManifestAsync(url, cancellationToken);
            var requested = string.IsNullOrWhiteSpace(languageCode) ? "auto" : languageCode.Trim();

            if (requested.Equals("auto", StringComparison.OrdinalIgnoreCase))
            {
                return manifest.Tracks.FirstOrDefault(t => !t.IsAutoGenerated)
                       ?? manifest.Tracks.FirstOrDefault();
            }

            var matching = manifest.Tracks
                .Where(t => t.Language.Code.Equals(requested, StringComparison.OrdinalIgnoreCase)
                            || t.Language.Code.StartsWith(requested + "-", StringComparison.OrdinalIgnoreCase)
                            || t.Language.Code.StartsWith(requested, StringComparison.OrdinalIgnoreCase))
                .ToList();

            // Prefer captions written by the uploader over YouTube's speech recognition.
            return matching.FirstOrDefault(t => !t.IsAutoGenerated) ?? matching.FirstOrDefault();
        }
        catch (OperationCanceledException)
        {
            throw;
        }
        catch
        {
            // Subtitles are optional; a failure here must never fail the download itself.
            return null;
        }
    }

    public async Task<string?> DownloadSubtitlesAsync(
        ClosedCaptionTrackInfo track,
        string srtFilePath,
        CancellationToken cancellationToken = default)
    {
        try
        {
            // YoutubeExplode always writes SubRip (SRT) formatted captions.
            await _youtube.Videos.ClosedCaptions.DownloadAsync(track, srtFilePath, null, cancellationToken);
            return srtFilePath;
        }
        catch (OperationCanceledException)
        {
            throw;
        }
        catch
        {
            return null;
        }
    }

    public async Task<StreamQualityOption> ResolveStreamsAsync(
        string videoUrl,
        string qualityPreference,
        CancellationToken cancellationToken = default)
    {
        var manifest = await _youtube.Videos.Streams.GetManifestAsync(videoUrl, cancellationToken);
        return SelectStreams(manifest, qualityPreference)
               ?? throw new InvalidOperationException("YouTube did not return any downloadable streams for this video.");
    }

    public async Task DownloadAsync(
        StreamQualityOption option,
        string outputFilePath,
        IReadOnlyList<ClosedCaptionTrackInfo>? embeddedSubtitles = null,
        IProgress<double>? progress = null,
        CancellationToken cancellationToken = default)
    {
        var outputDirectory = Path.GetDirectoryName(outputFilePath);
        if (!string.IsNullOrWhiteSpace(outputDirectory))
        {
            Directory.CreateDirectory(outputDirectory);
        }

        if (option.VideoStream == null && option.AudioStream != null)
        {
            if (outputFilePath.EndsWith(".mp3", StringComparison.OrdinalIgnoreCase))
            {
                await DownloadHighQualityMp3Async(option.AudioStream, outputFilePath, progress, cancellationToken);
            }
            else
            {
                await _youtube.Videos.Streams.DownloadAsync(option.AudioStream, outputFilePath, progress, cancellationToken);
            }

            return;
        }

        if (option.VideoStream == null)
        {
            throw new InvalidOperationException("No stream was selected for this download.");
        }

        var hasSubtitles = embeddedSubtitles is { Count: > 0 };
        if (!option.RequiresFfmpeg && !hasSubtitles)
        {
            await _youtube.Videos.Streams.DownloadAsync(option.VideoStream, outputFilePath, progress, cancellationToken);
            return;
        }

        var streamInfos = option.AudioStream != null && !ReferenceEquals(option.AudioStream, option.VideoStream)
            ? new IStreamInfo[] { option.VideoStream, option.AudioStream }
            : new IStreamInfo[] { option.VideoStream };

        // The converter only finds FFmpeg in the app folder or on PATH. On macOS neither covers
        // the FFmpeg we download to Application Support or Homebrew's /opt/homebrew/bin when the
        // app is launched from Finder, so the resolved path is always passed explicitly.
        var ffmpegPath = await FfmpegBootstrapper.EnsureFfmpegCliPathAsync(null, cancellationToken);
        var request = new ConversionRequestBuilder(outputFilePath)
            .SetFFmpegPath(ffmpegPath)
            .SetPreset(ConversionPreset.Fast)
            .Build();

        await _youtube.Videos.DownloadAsync(
            streamInfos,
            embeddedSubtitles ?? Array.Empty<ClosedCaptionTrackInfo>(),
            request,
            progress,
            cancellationToken);
    }

    /// <summary>
    /// Picks the streams for a quality preference. Streams whose container already matches the
    /// output are preferred, because FFmpeg can then copy them instead of re-encoding (which is
    /// slow for HD video). H.264 is preferred over AV1/VP9 for playback compatibility in
    /// QuickTime, Windows Media Player, TVs and phones.
    /// </summary>
    public static StreamQualityOption? SelectStreams(StreamManifest manifest, string qualityPreference)
    {
        var audioStreams = manifest.GetAudioOnlyStreams().ToList();
        var videoStreams = manifest.GetVideoOnlyStreams().ToList();
        var muxedStreams = manifest.GetMuxedStreams().ToList();

        if (IsAudioPreference(qualityPreference))
        {
            var audio = audioStreams.OrderByDescending(s => s.Bitrate).FirstOrDefault();
            return audio == null
                ? null
                : new StreamQualityOption
                {
                    DisplayName = $"MP3 · {audio.Bitrate.KiloBitsPerSecond:F0} kbps source",
                    AudioStream = audio,
                    OutputExtension = ".mp3",
                    RequiresFfmpeg = true
                };
        }

        if (qualityPreference == NativeVideoPreference)
        {
            var muxed = muxedStreams
                .OrderByDescending(s => s.VideoResolution.Area)
                .ThenBy(s => s.Container == Container.Mp4 ? 0 : 1)
                .FirstOrDefault();

            if (muxed != null)
            {
                return new StreamQualityOption
                {
                    DisplayName = $"{muxed.VideoQuality.Label} · {muxed.Container.Name.ToUpperInvariant()} (native)",
                    VideoStream = muxed,
                    AudioStream = muxed,
                    OutputExtension = "." + muxed.Container.Name,
                    RequiresFfmpeg = false
                };
            }

            // YouTube no longer offers a combined stream for many videos; merge instead of
            // failing or saving an audio-only stream as .mp4.
            return SelectAdaptive(videoStreams, audioStreams, muxedStreams, maxHeight: 1080, allowWebm: false);
        }

        var maxHeight = qualityPreference switch
        {
            Video1080pPreference => 1080,
            Video720pPreference => 720,
            _ => (int?)null
        };

        return SelectAdaptive(videoStreams, audioStreams, muxedStreams, maxHeight, allowWebm: maxHeight == null);
    }

    public static bool IsAudioPreference(string qualityPreference)
    {
        return qualityPreference.Contains("Audio", StringComparison.OrdinalIgnoreCase)
               || qualityPreference.Contains("MP3", StringComparison.OrdinalIgnoreCase);
    }

    private static StreamQualityOption? SelectAdaptive(
        IReadOnlyList<VideoOnlyStreamInfo> videoStreams,
        IReadOnlyList<AudioOnlyStreamInfo> audioStreams,
        IReadOnlyList<MuxedStreamInfo> muxedStreams,
        int? maxHeight,
        bool allowWebm)
    {
        var candidates = videoStreams
            .Where(s => maxHeight == null || s.VideoResolution.Height <= maxHeight)
            .ToList();

        if (candidates.Count == 0)
        {
            // The requested cap is below every adaptive stream; use the smallest available one.
            candidates = videoStreams
                .OrderBy(s => s.VideoResolution.Height)
                .Take(1)
                .ToList();
        }

        var bestHeight = candidates.Count > 0 ? candidates.Max(s => s.VideoResolution.Height) : 0;
        var bestMuxed = muxedStreams.OrderByDescending(s => s.VideoResolution.Area).FirstOrDefault();

        if (bestMuxed != null
            && bestMuxed.VideoResolution.Height >= bestHeight
            && (maxHeight == null || bestMuxed.VideoResolution.Height <= maxHeight))
        {
            return new StreamQualityOption
            {
                DisplayName = $"{bestMuxed.VideoQuality.Label} · {bestMuxed.Container.Name.ToUpperInvariant()} (native)",
                VideoStream = bestMuxed,
                AudioStream = bestMuxed,
                OutputExtension = "." + bestMuxed.Container.Name,
                RequiresFfmpeg = false
            };
        }

        if (candidates.Count == 0)
        {
            return null;
        }

        var topCandidates = candidates
            .Where(s => s.VideoResolution.Height == bestHeight)
            .ToList();

        var mp4Candidates = topCandidates.Where(s => s.Container == Container.Mp4).ToList();
        List<VideoOnlyStreamInfo> pool;

        if (mp4Candidates.Count > 0)
        {
            pool = mp4Candidates;
        }
        else if (allowWebm)
        {
            pool = topCandidates;
        }
        else
        {
            // Step down to the best MP4 stream rather than forcing a slow VP9 re-encode.
            var bestMp4 = candidates
                .Where(s => s.Container == Container.Mp4)
                .OrderByDescending(s => s.VideoResolution.Height)
                .FirstOrDefault();

            pool = bestMp4 != null
                ? candidates.Where(s => s.Container == Container.Mp4 && s.VideoResolution.Height == bestMp4.VideoResolution.Height).ToList()
                : topCandidates;
        }

        var video = pool
            .OrderByDescending(s => s.VideoQuality.Framerate)
            .ThenBy(s => GetVideoCodecRank(s.VideoCodec))
            .ThenByDescending(s => s.Bitrate)
            .First();

        var container = video.Container == Container.Mp4 ? Container.Mp4 : video.Container;
        var audio = audioStreams
                        .Where(s => s.Container == container)
                        .OrderByDescending(s => s.Bitrate)
                        .FirstOrDefault()
                    ?? audioStreams.OrderByDescending(s => s.Bitrate).FirstOrDefault();

        return new StreamQualityOption
        {
            DisplayName = $"{video.VideoQuality.Label} · {container.Name.ToUpperInvariant()} · {GetFriendlyCodecName(video.VideoCodec)}",
            VideoStream = video,
            AudioStream = audio,
            OutputExtension = "." + container.Name,
            RequiresFfmpeg = true
        };
    }

    private static int GetVideoCodecRank(string codec)
    {
        if (codec.StartsWith("avc", StringComparison.OrdinalIgnoreCase)) return 0;
        if (codec.StartsWith("av01", StringComparison.OrdinalIgnoreCase)) return 1;
        if (codec.StartsWith("vp9", StringComparison.OrdinalIgnoreCase) || codec.StartsWith("vp09", StringComparison.OrdinalIgnoreCase)) return 2;
        return 3;
    }

    private static string GetFriendlyCodecName(string codec)
    {
        if (codec.StartsWith("avc", StringComparison.OrdinalIgnoreCase)) return "H.264";
        if (codec.StartsWith("av01", StringComparison.OrdinalIgnoreCase)) return "AV1";
        if (codec.StartsWith("vp9", StringComparison.OrdinalIgnoreCase) || codec.StartsWith("vp09", StringComparison.OrdinalIgnoreCase)) return "VP9";
        return codec;
    }

    private async Task DownloadHighQualityMp3Async(
        IStreamInfo audioStream,
        string outputFilePath,
        IProgress<double>? progress,
        CancellationToken cancellationToken)
    {
        var outputDirectory = Path.GetDirectoryName(outputFilePath);
        if (!string.IsNullOrWhiteSpace(outputDirectory))
        {
            Directory.CreateDirectory(outputDirectory);
        }

        var sourceExtension = audioStream.Container.Name;
        var tempPath = Path.Combine(
            string.IsNullOrWhiteSpace(outputDirectory) ? Path.GetTempPath() : outputDirectory,
            $".{Guid.NewGuid():N}.source.{sourceExtension}");

        try
        {
            var downloadProgress = progress == null
                ? null
                : new Progress<double>(p => progress.Report(Math.Min(p * 0.92, 0.92)));

            await _youtube.Videos.Streams.DownloadAsync(audioStream, tempPath, downloadProgress, cancellationToken);

            var ffmpegPath = await FfmpegBootstrapper.EnsureFfmpegCliPathAsync(null, cancellationToken);
            await ConvertAudioToHighQualityMp3Async(ffmpegPath, tempPath, outputFilePath, cancellationToken);
            progress?.Report(1);
        }
        finally
        {
            TryDeleteFile(tempPath);
        }
    }

    private static async Task ConvertAudioToHighQualityMp3Async(
        string ffmpegPath,
        string inputPath,
        string outputFilePath,
        CancellationToken cancellationToken)
    {
        var processInfo = new ProcessStartInfo
        {
            FileName = ffmpegPath,
            UseShellExecute = false,
            RedirectStandardError = true,
            RedirectStandardOutput = true,
            RedirectStandardInput = true,
            CreateNoWindow = true
        };

        processInfo.ArgumentList.Add("-hide_banner");
        processInfo.ArgumentList.Add("-nostdin");
        processInfo.ArgumentList.Add("-y");
        processInfo.ArgumentList.Add("-i");
        processInfo.ArgumentList.Add(inputPath);
        processInfo.ArgumentList.Add("-vn");
        processInfo.ArgumentList.Add("-map_metadata");
        processInfo.ArgumentList.Add("-1");
        processInfo.ArgumentList.Add("-codec:a");
        processInfo.ArgumentList.Add("libmp3lame");
        processInfo.ArgumentList.Add("-b:a");
        processInfo.ArgumentList.Add("320k");
        processInfo.ArgumentList.Add(outputFilePath);

        using var process = new Process { StartInfo = processInfo };
        var output = new StringBuilder();
        var outputLock = new object();

        void Capture(string? line)
        {
            if (string.IsNullOrWhiteSpace(line))
            {
                return;
            }

            lock (outputLock)
            {
                output.AppendLine(line);
            }
        }

        process.OutputDataReceived += (_, e) => Capture(e.Data);
        process.ErrorDataReceived += (_, e) => Capture(e.Data);

        try
        {
            if (!process.Start())
            {
                throw new InvalidOperationException($"Could not start FFmpeg at '{ffmpegPath}'.");
            }
        }
        catch (System.ComponentModel.Win32Exception ex)
        {
            throw new InvalidOperationException(FfmpegBootstrapper.DescribeStartFailure(ffmpegPath, ex), ex);
        }

        process.BeginOutputReadLine();
        process.BeginErrorReadLine();

        // Without this FFmpeg keeps running (and keeps the output file locked on Windows) after
        // the user pauses or cancels, or after the app quits. The callback runs synchronously
        // inside Cancel(), so it also fires during shutdown.
        using (cancellationToken.Register(() => TryKill(process)))
        {
            try
            {
                await process.WaitForExitAsync(cancellationToken);
            }
            catch (OperationCanceledException)
            {
                TryKill(process);
                TryDeleteFile(outputFilePath);
                throw;
            }
        }

        if (process.ExitCode != 0)
        {
            string details;
            lock (outputLock)
            {
                details = output.ToString().Trim();
            }

            if (details.Length > 800)
            {
                details = details[^800..];
            }

            throw new InvalidOperationException(string.IsNullOrWhiteSpace(details)
                ? $"FFmpeg exited with code {process.ExitCode}."
                : $"FFmpeg exited with code {process.ExitCode}: {details}");
        }
    }

    private static void TryKill(Process process)
    {
        try
        {
            if (!process.HasExited)
            {
                process.Kill(entireProcessTree: true);
                process.WaitForExit(3000);
            }
        }
        catch
        {
        }
    }

    private static void TryDeleteFile(string path)
    {
        try
        {
            if (File.Exists(path))
            {
                File.Delete(path);
            }
        }
        catch
        {
        }
    }
}
